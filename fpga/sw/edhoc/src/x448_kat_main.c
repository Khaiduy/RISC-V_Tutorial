/* x448_kat_main.c — RV32 KAT + cycle benchmark for the Monocypher-style X448.
 *
 * Part 1 (KAT): runs the RFC 7748 §5.2/§6.2 vectors that PASS on host gcc.
 *   PASS on the FPGA  -> X448 is correct on the real RV32 target.
 *   FAIL on the FPGA  -> RV32-specific bug (32-bit int, alignment, LTO).
 *
 * Part 2 (BENCH): times crypto_x448 vs wolfSSL curve448() with rdcycle, to get
 *   the speed number vs wolfSSL's ~400 M cycles/scalarmult (see BENCHMARKS.md).
 *
 * Build:  make x448_test
 * Run:    load like any edhoc_* binary; UART prints results.
 */
#include <stdint.h>
#include <string.h>
#include "platform.h"
#include "kprintf.h"
#include "uart.h"                        /* UART_REG_DIV, UART_TXEN */

#include "monocypher.h"                  /* crypto_x448 */
#include "wolfssl/wolfcrypt/settings.h"
#include "wolfssl/wolfcrypt/fe_448.h"    /* curve448(out, scalar, point) */

static inline uint32_t read_cycles(void){
    uint32_t c; __asm__ volatile ("rdcycle %0" : "=r"(c)); return c;
}

static int cmp(const uint8_t *a, const uint8_t *b, int n){ return memcmp(a,b,n)==0; }
static void prhex(const char *l, const uint8_t *b, int n){
    kprintf("%s", l); for (int i=0;i<n;i++) kprintf("%02x", b[i]); kprintf("\r\n");
}

