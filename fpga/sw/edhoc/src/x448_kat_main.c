static void uart_drain(void){ for (volatile uint32_t i=0;i<6000000;i++){} } /* ~120 ms @ 50 MHz */

int main(void){
    /* Terminal UART (UART0) baud init — REQUIRED before any kprintf, else the
     * UART runs at the reset divisor and the host sees garbage. 50 MHz / 868 =
     * 57600 baud. (UART1 = inter-board link; unused by this standalone KAT.) */
    REG32(uart, UART_REG_DIV)    = 868;
    REG32(uart, UART_REG_TXCTRL) = UART_TXEN;

    kprintf("\r\n=== X448 KAT + bench on RV32 ===\r\n");
    int fails = 0;
    uint8_t out[56], a_pub[56], b_pub[56], ss_a[56], ss_b[56];

    /* ---- Part 1: KAT ---- */
    crypto_x448(out, v1_scalar, v1_u);
    if (cmp(out, v1_out, 56)) kprintf("RFC7748 5.2 #1   PASS\r\n");
    else { kprintf("RFC7748 5.2 #1   FAIL\r\n"); prhex("  got ",out,56); fails++; }

    crypto_x448_public_key(a_pub, a_priv);
    crypto_x448_public_key(b_pub, b_priv);
    crypto_x448(ss_a, a_priv, b_pub);
    crypto_x448(ss_b, b_priv, a_pub);
    if (cmp(ss_a, ss_b, 56)) kprintf("ECDH symmetric   PASS\r\n");
    else { kprintf("ECDH symmetric   FAIL\r\n"); fails++; }
    if (cmp(ss_a, ss_exp, 56)) kprintf("RFC7748 6.2 DH   PASS\r\n");
    else { kprintf("RFC7748 6.2 DH   FAIL\r\n"); prhex("  got ",ss_a,56); fails++; }

    /* cross-check vs wolfSSL curve448 on the §5.2 input */
    uint8_t wolf[56];
    if (curve448(wolf, v1_scalar, v1_u) == 0 && cmp(wolf, v1_out, 56))
        kprintf("wolfSSL curve448 PASS (oracle agrees)\r\n");
    else { kprintf("wolfSSL curve448 FAIL\r\n"); fails++; }

    kprintf(fails ? "KAT: FAILURES\r\n" : "KAT: ALL PASS\r\n");
    uart_drain();

    /* ---- Part 2: cycle bench ----
     * Compute BOTH timings first (no UART during measurement), then print a
     * compact summary repeatedly with drains so at least one clean copy
     * survives the UART byte loss seen on long bursts.
     */
    uint32_t t0,t1;
    t0 = read_cycles(); crypto_x448(out,  a_priv, b_pub); t1 = read_cycles();
    unsigned long mono_cyc = (unsigned long)(t1 - t0);
    t0 = read_cycles(); (void)curve448(wolf, a_priv, b_pub); t1 = read_cycles();
    unsigned long wolf_cyc = (unsigned long)(t1 - t0);
    int agree = cmp(out, wolf, 56);

    for (int rep = 0; rep < 3; rep++) {
        uart_drain();
        kprintf("\r\nBENCH x448 (rep %lu):\r\n", (unsigned long)rep);
        uart_drain();
        kprintf("  mono crypto_x448 = %lu cyc\r\n", mono_cyc);
        uart_drain();
        kprintf("  wolf curve448    = %lu cyc\r\n", wolf_cyc);
        uart_drain();
        kprintf("  outputs agree    = %s\r\n", agree ? "YES" : "NO");
        uart_drain();
    }

    if (!agree) fails++;
    kprintf(fails ? "\r\nEDHOC FAIL\r\n" : "\r\nEDHOC OK\r\n");  /* loader markers */
    uart_drain();
    for(;;){}
    return 0;
}
